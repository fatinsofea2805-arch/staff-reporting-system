CREATE TABLE IF NOT EXISTS `admin` (
  `ADMIN_ID` INTEGER PRIMARY KEY AUTOINCREMENT,
  `ADMIN_EMAIL` TEXT COLLATE NOCASE NOT NULL,
  `ADMIN_PASSWORD` TEXT NOT NULL,
  `LOGGED_IN` INTEGER DEFAULT '0',
  UNIQUE (`ADMIN_EMAIL`)
);

CREATE TABLE IF NOT EXISTS `emergency` (
  `LEAVE_ID` TEXT NOT NULL,
  `LEAVE_DATE` TEXT NOT NULL,
  `LEAVE_TIME` TEXT NULL DEFAULT (datetime('now', '+8 hours')),
  `LEAVE_TYPE` TEXT NOT NULL CHECK (`LEAVE_TYPE` IN ('Medical','Family Emergency','Personal','Other')),
  `LEAVE_DURATION` TEXT NOT NULL CHECK (`LEAVE_DURATION` IN ('Full Day','Half Day','Hourly')),
  `LEAVE_HOURS` INTEGER DEFAULT NULL,
  `OTHER_LEAVE_DETAILS` text,
  `FILE_NAME` TEXT DEFAULT NULL,
  `FILE_TYPE` TEXT DEFAULT NULL,
  `LEAVE_STATUS` TEXT DEFAULT 'Not Seen' CHECK (`LEAVE_STATUS` IN ('Not Seen','Seen')),
  `STAFF_ID` TEXT NOT NULL,
  PRIMARY KEY (`LEAVE_ID`),
  UNIQUE (`LEAVE_ID`)
);

CREATE TABLE IF NOT EXISTS `holiday` (
  `HOLIDAY_ID` TEXT NOT NULL,
  `HOLIDAY_NAME` TEXT NOT NULL,
  `HOLIDAY_TIME` TEXT NULL DEFAULT (datetime('now', '+8 hours')),
  `START_DATE` TEXT NOT NULL,
  `END_DATE` TEXT NOT NULL,
  `HOLIDAY_DURATION` INTEGER DEFAULT NULL,
  `ADMIN_ID` INTEGER NOT NULL,
  PRIMARY KEY (`HOLIDAY_ID`)
);

CREATE TABLE IF NOT EXISTS `lateness` (
  `LATENESS_ID` TEXT NOT NULL,
  `LATENESS_TIME` TEXT NULL DEFAULT (datetime('now', '+8 hours')),
  `LATENESS_DATE` TEXT NOT NULL,
  `LATENESS_REASON` text,
  `FILE_NAME` TEXT DEFAULT NULL,
  `FILE_TYPE` TEXT DEFAULT NULL,
  `LATENESS_STATUS` TEXT DEFAULT 'Not Seen' CHECK (`LATENESS_STATUS` IN ('Seen','Not Seen')),
  `STAFF_ID` TEXT DEFAULT NULL,
  PRIMARY KEY (`LATENESS_ID`)
);

CREATE TABLE IF NOT EXISTS `staff` (
  `STAFF_ID` TEXT NOT NULL,
  `STAFF_NAME` TEXT NOT NULL,
  `DEPARTMENT` TEXT DEFAULT NULL,
  `UNIT` TEXT DEFAULT NULL,
  `POSITION` TEXT DEFAULT NULL,
  `PHONE_NUM` TEXT DEFAULT NULL,
  `STAFF_EMAIL` TEXT COLLATE NOCASE NOT NULL,
  `STAFF_PASSWORD` TEXT NOT NULL,
  `PROFILE_PIC` TEXT DEFAULT NULL,
  PRIMARY KEY (`STAFF_ID`),
  UNIQUE (`STAFF_EMAIL`)
);

CREATE INDEX `emergency_STAFF_ID` ON `emergency` (`STAFF_ID`);

CREATE INDEX `holiday_ADMIN_ID` ON `holiday` (`ADMIN_ID`);

CREATE INDEX `lateness_STAFF_ID` ON `lateness` (`STAFF_ID`);
